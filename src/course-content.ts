/**
 * Helper to get complete chapter content by film ID or index
 */
export function getChapterContent(idOrIndex: string | number): ChapterContent {
  if (typeof idOrIndex === 'number') {
    return CHAPTER_CONTENTS[idOrIndex % CHAPTER_CONTENTS.length];
  }
  return CHAPTER_CONTENTS.find((c) => c.id === idOrIndex) || CHAPTER_CONTENTS[0];
}
